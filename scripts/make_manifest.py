#!/usr/bin/env python
"""Write results/MANIFEST.md: every committed result file with its producer, config and seed."""
from __future__ import annotations

import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RULES = [  # (path prefix, script, configuration, seeds)
    ("results/audit/las_files.csv", "scripts/audit_pass1.py", "none", "deterministic"),
    ("results/audit/curve_catalog.csv", "scripts/audit_pass1.py", "none", "deterministic"),
    ("results/audit/premise_check.json", "scripts/audit_report.py", "none", "deterministic"),
    ("results/audit/vintage_summary.json", "scripts/audit_report.py", "none", "deterministic"),
    ("results/audit/", "scripts/audit_pass2.py", "configs/mnemonics.yaml", "deterministic"),
    ("results/synthetic/", "scripts/make_synthetic.py", "configs/cpu_small.yaml", "0"),
    ("results/identifiability/", "scripts/run_identifiability.py --suite v1", "configs/cpu_small.yaml",
     "benchmark 0,1,2; optimiser 1000+seed"),
    ("results/identifiability_v2/", "scripts/run_identifiability.py --suite v2", "configs/cpu_small.yaml",
     "benchmark 0,1,2; optimiser 1000+seed"),
    ("results/pay_indicator_benchmark/", "scripts/run_identifiability.py --suite v3",
     "configs/cpu_small.yaml", "benchmark 0,1,2; optimiser 1000+seed"),
    ("results/splits/dataset_fingerprint", "chertfield.data.real.fingerprint", "none", "deterministic"),
    ("results/splits/", "scripts/make_splits.py", "none", "20261112"),
    ("results/real/diagnostics_exploratory.json", "scripts/diagnose_real.py (EXPLORATORY)", "none",
     "deterministic"),
    ("results/real/evaluation.json", "scripts/eval_real.py", "configs/scale_up.yaml", "bootstrap 20261112"),
    ("results/real/well_scores.csv", "scripts/eval_real.py", "configs/scale_up.yaml", "bootstrap 20261112"),
    ("results/real/run_logs/", "scripts/run_lab.bat full (lab PC)", "configs/scale_up.yaml", "n/a"),
    ("results/real/", "scripts/train_real.py (lab PC, GPU)", "configs/scale_up.yaml",
     "ensemble 0..9; set_seed(seed*100+fold)"),
]


def main() -> None:
    rows = []
    for f in sorted((ROOT / "results").rglob("*")):
        if not f.is_file() or f.name == "MANIFEST.md":
            continue
        rel = f.relative_to(ROOT).as_posix()
        if rel.startswith("results/standin/"):
            continue
        script, cfg, seed = next(((s, c, d) for p, s, c, d in RULES if rel.startswith(p)), ("?", "?", "?"))
        digest = hashlib.sha256(f.read_bytes().replace(b"\r\n", b"\n")).hexdigest()[:12]
        rows.append(f"| `{rel}` | {f.stat().st_size:,} | `{digest}` | {script} | {cfg} | {seed} |")
    head = ("# Results manifest\n\nGenerated by `scripts/make_manifest.py`. SHA-256 (first 12 hex digits) is "
            "computed after normalising line endings.\n\n"
            "| File | Bytes | SHA-256 | Produced by | Config | Seeds |\n"
            "|---|---|---|---|---|---|\n")
    (ROOT / "results/MANIFEST.md").write_text(head + "\n".join(rows) + "\n")
    print(len(rows), "files listed;", sum("| ? |" in r for r in rows), "without a rule")


if __name__ == "__main__":
    main()
